class BaselineMirror:
    """
    Generates traffic that is statistically indistinguishable from
    a target network's normal baseline.
    
    Uses 's statistical knowledge (from 314M transition analysis)
    to model and reproduce normal traffic distributions.
    """
    
    def __init__(self, baseline: NetworkBaseline = None):
        self.baseline = baseline or NetworkBaseline()
        self._rng = random.Random()
        self._traffic_history = []  # Rolling window of generated traffic stats
    
    def sample_packet_size(self) -> int:
        """Generate packet size matching the baseline Weibull distribution."""
        b = self.baseline
        size = self._rng.weibullvariate(b.packet_size_scale, b.packet_size_shape)
        # Clamp to realistic range
        return max(40, min(1500, int(size)))
    
    def sample_inter_arrival(self) -> float:
        """Generate inter-arrival time matching baseline LogNormal distribution."""
        b = self.baseline
        iat = self._rng.lognormvariate(b.iat_mu, b.iat_sigma)
        return max(0.001, iat)  # Min 1ms
    
    # Protocols that have Deep Phantom encoders
    COVERT_CARRIERS = ["dns", "icmp", "tls_ext", "ws_ping", "timing"]

    def sample_protocol(self, exclude_http: bool = True) -> str:
        """
        Sample a protocol from the baseline distribution.
        If exclude_http=True, maps to covert carriers only.
        """
        if exclude_http:
            # Only use carriers with actual encoders
            return self._rng.choice(self.COVERT_CARRIERS)

        b = self.baseline
        protocols = list(b.protocol_mix.keys())
        weights = list(b.protocol_mix.values())
        protocol = self._rng.choices(protocols, weights=weights, k=1)[0]

        # Map non-covert protocols to ones we have encoders for
        if protocol in ("http", "other", "ntp"):
            return self._rng.choice(self.COVERT_CARRIERS)
        if protocol == "ws":
            return "ws_ping"
        if protocol == "tls":
            return "tls_ext"

        return protocol if protocol in self.COVERT_CARRIERS else self._rng.choice(self.COVERT_CARRIERS)
    
    def sample_device(self) -> dict:
        """Sample a device profile matching baseline distribution."""
        b = self.baseline
        devices = list(b.device_mix.keys())
        weights = list(b.device_mix.values())
        device = self._rng.choices(devices, weights=weights, k=1)[0]
        
        profiles = {
            "desktop_windows": {"os": "Windows 10/11", "browser": "chrome", "screen": "1920x1080"},
            "desktop_mac": {"os": "macOS 14/15", "browser": "safari", "screen": "2560x1440"},
            "mobile_android": {"os": "Android 14", "browser": "chrome_mobile", "screen": "412x915"},
            "mobile_ios": {"os": "iOS 18", "browser": "safari_mobile", "screen": "393x852"},
            "tablet": {"os": "iPadOS 17", "browser": "safari", "screen": "1024x1366"},
        }
        return profiles.get(device, profiles["desktop_windows"])
    
    def sample_geo(self) -> dict:
        """Sample geographic location from baseline distribution."""
        b = self.baseline
        regions = list(b.geo_mix.keys())
        weights = list(b.geo_mix.values())
        region = self._rng.choices(regions, weights=weights, k=1)[0]
        
        geo_data = {
            "US": {"tz": "America/New_York", "locale": "en-US"},
            "EU": {"tz": "Europe/Berlin", "locale": "en-GB"},
            "AS": {"tz": "Asia/Tokyo", "locale": "ja-JP"},
            "SA": {"tz": "America/Sao_Paulo", "locale": "pt-BR"},
            "AF": {"tz": "Africa/Lagos", "locale": "en-NG"},
            "OC": {"tz": "Australia/Sydney", "locale": "en-AU"},
        }
        return {"region": region, **geo_data.get(region, geo_data["US"])}
    
    def activity_multiplier(self, timestamp: float = None) -> float:
        """Get activity level for current hour (0-1)."""
        if timestamp is None:
            timestamp = time.time()
        hour = time.localtime(timestamp).tm_hour
        return self.baseline.hourly_pattern.get(hour, 0.5)
    
    def should_act(self) -> bool:
        """Probabilistic decision: should we act now based on baseline patterns?"""
        activity = self.activity_multiplier()
        # Add randomness so pattern isn't perfectly predictable
        noise = self._rng.uniform(-0.15, 0.15)
        threshold = max(0.05, activity + noise)
        return self._rng.random() < threshold


